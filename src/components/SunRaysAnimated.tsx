interface Props {
  /** Rendered size in px (square) */
  size?: number;
  /** Seconds each sun is displayed before cycling */
  cycleDuration?: number;
  /** Stroke color (default: gold #C8AE69) */
  strokeColor?: string;
  /** When true the SVG fills its parent container (ignores size) */
  fill?: boolean;
  className?: string;
}

export function SunRaysAnimated({
  size = 240,
  cycleDuration = 4,
  strokeColor = "#C8AE69",
  fill = false,
  className = "",
}: Props) {
  const uid = useId().replace(/:/g, "");
  const [idx, setIdx] = useState(0);
  const [visible, setVisible] = useState(true);

  useEffect(() => {
    const timer = setInterval(() => {
      setVisible(false);
      setTimeout(() => {
        setIdx((i) => (i + 1) % SUNS.length);
        setVisible(true);
      }, 150);
    }, cycleDuration * 1000);
    return () => clearInterval(timer);
  }, [cycleDuration]);

  const cfg = CONFIGS[idx];
  const Sun = SUNS[idx];

  return (
    <>
      <style>{`
        @keyframes sr-cw-${uid}  { from{transform:rotate(0deg)}    to{transform:rotate(360deg)} }
        @keyframes sr-ccw-${uid} { from{transform:rotate(0deg)}    to{transform:rotate(-360deg)} }
        @keyframes sr-draw-${uid} {
          from { stroke-dashoffset: 600; }
          to   { stroke-dashoffset: 0; }
        }
        @keyframes sr-pulse-${uid} {
          0%,100% { transform: scale(1); }
          50%     { transform: scale(1.07); }
        }
        @keyframes sr-in-${uid}  { from{transform:scale(0.94)} to{transform:scale(1)} }
        @keyframes sr-out-${uid} { from{transform:scale(1)}    to{transform:scale(1.04)} }

        .sr-wrap-${uid} path {
          stroke: ${strokeColor};
          stroke-miterlimit: 10;
          stroke-linecap: round;
          fill: none;
          stroke-dasharray: 600;
          animation: sr-draw-${uid} ${cfg.drawDur}s ease forwards;
        }
        .sr-wrap-${uid} {
          fill: none;
        }
      `}</style>

      <svg
        key={idx}
        width={fill ? undefined : size}
        height={fill ? undefined : size}
        viewBox={cfg.viewBox}
        fill="none"
        aria-hidden="true"
        className={`sr-wrap-${uid} ${className}`}
        style={{
          display: "block",
          ...(fill ? { width: "100%", height: "100%" } : {}),
          animation: `${visible ? `sr-in-${uid}` : `sr-out-${uid}`} 0.15s ease forwards`,
        }}
      >
        <g
          style={{
            transformOrigin: `${cfg.cx}px ${cfg.cy}px`,
            animation: [
              `${cfg.rotDir === 1 ? `sr-cw-${uid}` : `sr-ccw-${uid}`} ${cfg.rotDur}s linear infinite`,
              cfg.scaleDur > 0 ? `sr-pulse-${uid} ${cfg.scaleDur}s ease-in-out infinite` : "",
            ]
              .filter(Boolean)
              .join(", "),
          }}
        >
          <Sun />
        </g>
      </svg>
    </>
  );
}
